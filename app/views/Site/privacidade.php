                <h2 id="s1">1. Introdução</h2>
                <p>A Mecanize valoriza a privacidade, a segurança e a transparência no tratamento de dados pessoais.</p>
                <p>Esta Política de Privacidade explica como coletamos, utilizamos, armazenamos, protegemos e tratamos as informações de nossos clientes e usuários durante a utilização da plataforma.</p>
                <p>Ao utilizar nossos serviços, o usuário declara estar ciente desta Política de Privacidade.</p>

                <h2 id="s2">2. Quem somos</h2>
                <p>A Mecanize é uma plataforma SaaS (Software as a Service) desenvolvida para automatizar e modernizar a gestão de oficinas mecânicas, oferecendo recursos inteligentes para administração de ordens de serviço, clientes, veículos, estoque, financeiro e demais processos operacionais.</p>

                <h2 id="s3">3. Quais dados coletamos</h2>
                <p>Podemos coletar informações como:</p>

                <h3>Dados cadastrais</h3>
                <ul>
                    <li>Nome;</li>
                    <li>E-mail;</li>
                    <li>Telefone;</li>
                    <li>CPF ou CNPJ, quando necessário;</li>
                    <li>Endereço;</li>
                    <li>Dados da empresa contratante.</li>
                </ul>

                <h3>Dados operacionais</h3>
                <p>Durante a utilização da plataforma poderão ser armazenados:</p>
                <ul>
                    <li>Cadastro de clientes;</li>
                    <li>Cadastro de veículos;</li>
                    <li>Ordens de serviço;</li>
                    <li>Estoque;</li>
                    <li>Produtos;</li>
                    <li>Serviços;</li>
                    <li>Informações financeiras;</li>
                    <li>Relatórios;</li>
                    <li>Demais registros inseridos pelo cliente.</li>
                </ul>

                <h3>Dados técnicos</h3>
                <p>Também poderão ser coletados automaticamente:</p>
                <ul>
                    <li>Endereço IP;</li>
                    <li>Data e horário de acesso;</li>
                    <li>Navegador utilizado;</li>
                    <li>Sistema operacional;</li>
                    <li>Informações do dispositivo;</li>
                    <li>Registros de atividades (logs).</li>
                </ul>

                <h2 id="s4">4. Finalidade do tratamento dos dados</h2>
                <p>Os dados coletados são utilizados para:</p>
                <ul>
                    <li>fornecer os serviços contratados;</li>
                    <li>autenticar usuários;</li>
                    <li>garantir a segurança da plataforma;</li>
                    <li>armazenar informações da oficina;</li>
                    <li>disponibilizar funcionalidades do sistema;</li>
                    <li>realizar cobranças;</li>
                    <li>prestar suporte técnico;</li>
                    <li>desenvolver melhorias;</li>
                    <li>cumprir obrigações legais;</li>
                    <li>prevenir fraudes e acessos não autorizados.</li>
                </ul>
                <p>A Mecanize utiliza apenas os dados necessários para a execução de suas atividades.</p>

                <h2 id="s5">5. Base legal</h2>
                <p>O tratamento de dados pessoais ocorre em conformidade com a Lei Geral de Proteção de Dados Pessoais.</p>
                <p>As principais bases legais utilizadas são:</p>
                <ul>
                    <li>execução de contrato;</li>
                    <li>cumprimento de obrigação legal;</li>
                    <li>exercício regular de direitos;</li>
                    <li>legítimo interesse;</li>
                    <li>consentimento, quando exigido pela legislação.</li>
                </ul>

                <h2 id="s6">6. Compartilhamento de informações</h2>
                <p>A Mecanize não vende dados pessoais.</p>
                <p>Os dados somente poderão ser compartilhados quando necessário para:</p>
                <ul>
                    <li>funcionamento da infraestrutura tecnológica;</li>
                    <li>armazenamento em serviços de nuvem;</li>
                    <li>processamento de pagamentos;</li>
                    <li>cumprimento de determinações legais;</li>
                    <li>atendimento de autoridades competentes.</li>
                </ul>
                <p>Todos os parceiros utilizados devem adotar medidas adequadas de segurança e proteção das informações.</p>

                <h2 id="s7">7. Armazenamento dos dados</h2>
                <p>As informações são armazenadas em infraestrutura tecnológica segura, utilizando mecanismos modernos de proteção e controle de acesso.</p>
                <p>A Mecanize adota medidas técnicas e administrativas para reduzir riscos de acesso não autorizado, alteração, perda, destruição ou divulgação indevida dos dados.</p>
                <p>Embora sejam empregados elevados padrões de segurança, nenhum sistema é totalmente imune a falhas ou ataques.</p>

                <h2 id="s8">8. Tempo de retenção</h2>
                <p>Os dados permanecerão armazenados enquanto forem necessários para:</p>
                <ul>
                    <li>execução dos serviços contratados;</li>
                    <li>cumprimento de obrigações legais;</li>
                    <li>atendimento de solicitações do cliente;</li>
                    <li>resolução de eventuais disputas.</li>
                </ul>
                <p>Em caso de cancelamento da assinatura, os dados poderão permanecer armazenados até que o cliente solicite sua exclusão ou conforme exigido pela legislação aplicável.</p>

                <h2 id="s9">9. Suspensão por inadimplência</h2>
                <p>Em caso de inadimplência, o acesso ao sistema poderá ser suspenso após o período de tolerância estabelecido pela Mecanize.</p>
                <p>Durante esse período:</p>
                <ul>
                    <li>os dados permanecem armazenados;</li>
                    <li>nenhuma informação é perdida;</li>
                    <li>o acesso poderá ser restabelecido após a regularização dos pagamentos.</li>
                </ul>

                <h2 id="s10">10. Direitos do titular</h2>
                <p>Nos termos da LGPD, o titular dos dados poderá solicitar:</p>
                <ul>
                    <li>confirmação da existência de tratamento;</li>
                    <li>acesso aos dados;</li>
                    <li>correção de informações incompletas ou incorretas;</li>
                    <li>anonimização, bloqueio ou eliminação quando aplicável;</li>
                    <li>portabilidade dos dados, quando cabível;</li>
                    <li>informações sobre compartilhamento;</li>
                    <li>revogação do consentimento, quando essa for a base legal utilizada.</li>
                </ul>
                <p>As solicitações serão analisadas conforme a legislação vigente.</p>

                <h2 id="s11">11. Cookies</h2>
                <p>A plataforma poderá utilizar cookies e tecnologias semelhantes para:</p>
                <ul>
                    <li>manter a sessão do usuário;</li>
                    <li>melhorar a experiência de navegação;</li>
                    <li>aumentar a segurança;</li>
                    <li>lembrar preferências;</li>
                    <li>gerar estatísticas de utilização.</li>
                </ul>
                <p>O usuário poderá gerenciar cookies por meio das configurações do navegador, observando que a desativação de determinados cookies pode comprometer algumas funcionalidades.</p>

                <h2 id="s12">12. Responsabilidades do cliente</h2>
                <p>A oficina contratante é responsável pelos dados inseridos na plataforma.</p>
                <p>Quando cadastrar informações de clientes, funcionários ou terceiros, deverá observar a legislação aplicável e garantir que possui base legal para esse tratamento.</p>
                <p>A Mecanize atua como fornecedora da infraestrutura tecnológica necessária para o funcionamento da plataforma.</p>

                <h2 id="s13">13. Atualizações desta Política</h2>
                <p>Esta Política poderá ser modificada sempre que necessário para refletir alterações legais, regulatórias, técnicas ou operacionais.</p>
                <p>A versão mais recente permanecerá disponível na plataforma.</p>
                <p>O uso continuado dos serviços após a publicação das alterações representa ciência da nova versão.</p>

                <h2 id="s14">14. Contato</h2>
                <p>Solicitações relacionadas à privacidade, proteção de dados ou exercício de direitos poderão ser encaminhadas pelos canais oficiais de atendimento da Mecanize.</p>
                <p>Após a formalização da empresa, serão disponibilizados e-mail corporativo, canais de suporte e demais informações de contato.</p>

                <h2 id="s15">15. Disposições Finais</h2>
                <p>A Mecanize reafirma seu compromisso com a proteção da privacidade, da segurança da informação e da transparência no tratamento de dados pessoais.</p>
                <p>Nosso objetivo é oferecer uma plataforma confiável, moderna e alinhada à legislação brasileira, proporcionando aos clientes uma experiência segura durante toda a utilização dos nossos serviços.</p>

