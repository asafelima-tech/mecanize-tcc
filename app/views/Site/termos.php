                <h2 id="s1">1. Introdução</h2>
                <p>Bem-vindo à <strong>Mecanize</strong>.</p>
                <p>A Mecanize é uma plataforma SaaS (Software as a Service) desenvolvida para modernizar, automatizar e facilitar a gestão de oficinas mecânicas por meio de uma solução inteligente, segura e personalizável.</p>
                <p>Ao utilizar a plataforma, o cliente declara ter lido, compreendido e aceitado integralmente estes Termos de Uso. Caso não concorde com qualquer disposição deste documento, não deverá utilizar os serviços oferecidos.</p>

                <h2 id="s2">2. Sobre a Mecanize</h2>
                <p>A Mecanize é uma startup brasileira fundada em 2026 com o propósito de transformar a administração de oficinas mecânicas através da tecnologia.</p>
                <p>Nossa missão é oferecer uma plataforma moderna que simplifique processos, reduza retrabalho, aumente a produtividade e permita que oficinas de todos os portes administrem seus serviços de forma mais eficiente.</p>
                <p>A plataforma poderá incluir, entre outros recursos:</p>
                <ul>
                    <li>Gestão de Ordens de Serviço;</li>
                    <li>Gestão de clientes;</li>
                    <li>Gestão de veículos;</li>
                    <li>Controle de estoque;</li>
                    <li>Gestão financeira;</li>
                    <li>Emissão de documentos;</li>
                    <li>Relatórios;</li>
                    <li>Painéis inteligentes;</li>
                    <li>Automações;</li>
                    <li>Recursos personalizados conforme a necessidade de cada oficina.</li>
                </ul>

                <h2 id="s3">3. Aceitação dos Termos</h2>
                <p>Ao criar uma conta, contratar qualquer plano ou utilizar a plataforma, o cliente concorda integralmente com estes Termos de Uso.</p>
                <p>O uso continuado da plataforma representa concordância com eventuais atualizações deste documento.</p>

                <h2 id="s4">4. Descrição dos Serviços</h2>
                <p>A Mecanize disponibiliza uma plataforma em modelo SaaS, acessada pela internet, destinada à gestão de oficinas mecânicas.</p>
                <p>Cada implantação poderá receber personalizações conforme as necessidades do cliente.</p>
                <p>Os serviços podem incluir:</p>
                <ul>
                    <li>implantação inicial;</li>
                    <li>personalização da plataforma;</li>
                    <li>suporte técnico;</li>
                    <li>manutenção corretiva;</li>
                    <li>atualizações;</li>
                    <li>melhorias contínuas;</li>
                    <li>hospedagem da aplicação;</li>
                    <li>armazenamento seguro das informações.</li>
                </ul>

                <h2 id="s5">5. Cadastro e Conta</h2>
                <p>O cliente é responsável por fornecer informações verdadeiras e mantê-las atualizadas.</p>
                <p>Cada usuário deverá manter sua senha em sigilo.</p>
                <p>O titular da conta é responsável por todas as atividades realizadas por meio de seu acesso.</p>
                <p>A Mecanize não se responsabiliza pelo uso indevido decorrente do compartilhamento de credenciais ou da falta de cuidados com a segurança da conta.</p>

                <h2 id="s6">6. Planos, Ativação e Assinaturas</h2>
                <p>A utilização da plataforma depende da contratação de um plano pago.</p>
                <p>A contratação poderá envolver:</p>
                <ul>
                    <li>taxa de ativação;</li>
                    <li>assinatura mensal.</li>
                </ul>
                <p>O valor da ativação será definido considerando fatores como:</p>
                <ul>
                    <li>complexidade da implantação;</li>
                    <li>personalizações solicitadas;</li>
                    <li>tempo de desenvolvimento;</li>
                    <li>custos técnicos;</li>
                    <li>mão de obra especializada.</li>
                </ul>
                <p>A mensalidade será definida conforme o porte da oficina, utilização da plataforma e serviços contratados.</p>
                <p>Os valores poderão ser atualizados mediante comunicação prévia ao cliente.</p>

                <h2 id="s7">7. Cancelamento</h2>
                <p>O cliente poderá solicitar o cancelamento da assinatura a qualquer momento.</p>
                <p>Para evitar a cobrança do próximo ciclo, recomenda-se que o cancelamento seja solicitado com antecedência mínima de 24 (vinte e quatro) horas da renovação automática.</p>
                <p>Valores já pagos referentes ao período vigente não serão reembolsados, salvo obrigação legal ou acordo específico entre as partes.</p>

                <h2 id="s8">8. Pagamentos e Inadimplência</h2>
                <p>O não pagamento da assinatura não gera cancelamento imediato da conta.</p>
                <p>Após o vencimento, o cliente continuará com acesso normal durante o período de tolerância de 48 (quarenta e oito) horas.</p>
                <p>Encerrado esse prazo:</p>
                <ul>
                    <li>o acesso será suspenso;</li>
                    <li>novas operações ficarão indisponíveis;</li>
                    <li>os dados permanecerão armazenados.</li>
                </ul>
                <p>O acesso será restabelecido após a regularização dos pagamentos.</p>

                <h2 id="s9">9. Dados do Cliente</h2>
                <p>Todos os dados cadastrados pertencem exclusivamente ao cliente.</p>
                <p>A Mecanize atua apenas como operadora da infraestrutura tecnológica necessária para armazenamento e processamento dessas informações.</p>
                <p>Os dados permanecerão armazenados mesmo durante a suspensão do serviço.</p>
                <p>A exclusão definitiva poderá ocorrer mediante solicitação do cliente ou conforme política interna da empresa.</p>

                <h2 id="s10">10. Responsabilidades do Cliente</h2>
                <p>É responsabilidade do cliente:</p>
                <ul>
                    <li>utilizar o sistema de forma legal;</li>
                    <li>manter seus dados atualizados;</li>
                    <li>conferir as informações cadastradas;</li>
                    <li>proteger suas credenciais de acesso;</li>
                    <li>respeitar estes Termos de Uso.</li>
                </ul>
                <p>A Mecanize não se responsabiliza por:</p>
                <ul>
                    <li>erros de cadastro;</li>
                    <li>informações incorretas inseridas pelos usuários;</li>
                    <li>prejuízos decorrentes da utilização inadequada da plataforma;</li>
                    <li>decisões administrativas tomadas exclusivamente com base nas informações registradas pelo próprio cliente.</li>
                </ul>

                <h2 id="s11">11. Responsabilidades da Mecanize</h2>
                <p>A Mecanize compromete-se a:</p>
                <ul>
                    <li>fornecer a plataforma contratada;</li>
                    <li>realizar manutenção corretiva quando necessária;</li>
                    <li>disponibilizar suporte técnico;</li>
                    <li>desenvolver melhorias contínuas;</li>
                    <li>proteger os dados armazenados;</li>
                    <li>atuar em conformidade com a legislação brasileira.</li>
                </ul>
                <p>Embora empregue boas práticas de segurança e confiabilidade, a Mecanize não garante que a plataforma estará totalmente livre de falhas, interrupções ou indisponibilidades ocasionais.</p>

                <h2 id="s12">12. Disponibilidade da Plataforma</h2>
                <p>A Mecanize envidará esforços para manter a plataforma disponível de forma contínua.</p>
                <p>Entretanto, poderão ocorrer interrupções temporárias em razão de:</p>
                <ul>
                    <li>manutenções preventivas;</li>
                    <li>manutenções corretivas;</li>
                    <li>atualizações;</li>
                    <li>falhas de infraestrutura;</li>
                    <li>problemas de conexão à internet;</li>
                    <li>eventos de força maior;</li>
                    <li>situações fora do controle da empresa.</li>
                </ul>
                <p>Sempre que possível, manutenções programadas serão comunicadas antecipadamente.</p>

                <h2 id="s13">13. Suporte Técnico</h2>
                <p>Os planos contratados incluem suporte técnico destinado ao funcionamento da plataforma.</p>
                <p>O suporte poderá contemplar:</p>
                <ul>
                    <li>esclarecimento de dúvidas;</li>
                    <li>auxílio na utilização do sistema;</li>
                    <li>correção de falhas;</li>
                    <li>manutenção;</li>
                    <li>orientação técnica.</li>
                </ul>
                <p>O suporte não inclui treinamentos personalizados, consultorias externas ou alterações que estejam fora do escopo contratado.</p>

